import { readFileSync, readdirSync, statSync } from "node:fs"
import { join, relative, resolve } from "node:path"
import { describe, expect, it } from "vitest"

import {
  DEMO_CONVERSATIONS,
  DEMO_NOTICE,
  DEMO_THREAD,
  SPECIALISTS,
  getConversation,
  getDemoThread,
  getSpecialist,
} from "@/lib/demo-data"

const APP_ROOT = resolve(__dirname, "..")

function collectStrings(value: unknown, out: string[] = []): string[] {
  if (typeof value === "string") {
    out.push(value)
    return out
  }
  if (Array.isArray(value)) {
    for (const entry of value) collectStrings(entry, out)
    return out
  }
  if (value && typeof value === "object") {
    for (const entry of Object.values(value)) collectStrings(entry, out)
    return out
  }
  return out
}

function sourceFiles(dir: string, out: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) {
      // Vendored registry components are licensed third-party sources, not our copy.
      if (relative(APP_ROOT, full) === join("components", "ui")) continue
      sourceFiles(full, out)
      continue
    }
    if (/\.(ts|tsx|css|svg|mjs)$/.test(entry)) out.push(full)
  }
  return out
}

describe("preloaded team", () => {
  it("exposes exactly the three specialists with stable ids", () => {
    expect(SPECIALISTS.map((s) => s.id)).toEqual(["vera", "kael", "nova"])
    expect(getSpecialist("vera").role).toBe("Analista de evidencia")
    expect(() => getSpecialist("ghost" as never)).toThrow(/Unknown specialist/)
  })

  it("never presents a profile as authority", () => {
    for (const specialist of SPECIALISTS) {
      expect(specialist.note.length).toBeGreaterThan(0)
    }
  })
})

describe("programmed conversations", () => {
  it("only references known specialists", () => {
    const known = new Set(SPECIALISTS.map((s) => s.id))
    for (const conversation of DEMO_CONVERSATIONS) {
      expect(conversation.participants.length).toBeGreaterThan(0)
      for (const participant of conversation.participants) {
        expect(known.has(participant)).toBe(true)
      }
    }
  })

  it("resolves conversations and rejects unknown ids", () => {
    expect(getConversation("caso-0142")?.title).toContain("Caso 0142")
    expect(getConversation("no-existe")).toBeNull()
  })

  it("keeps the rich thread for its own case only", () => {
    expect(getDemoThread("caso-0142")).toEqual(DEMO_THREAD)
    const other = getDemoThread("caso-0131")
    expect(other).not.toEqual(DEMO_THREAD)
    // Programmed threads must not share state between runs.
    expect(getDemoThread("caso-0131")).not.toBe(other)
  })

  it("labels every tool part and uses unique ids", () => {
    const ids = DEMO_THREAD.flatMap((message) =>
      message.parts.filter((part) => part.kind === "tool").map((part) => part.id)
    )
    expect(ids.length).toBeGreaterThan(0)
    expect(new Set(ids).size).toBe(ids.length)
  })
})

describe("financial safety wording", () => {
  const forbidden = [/authorized_simulated/i, /\bpaid\b/i, /pag[oó]\b/i, /pagado/i]

  it("declares the demo mode explicitly", () => {
    expect(DEMO_NOTICE).toMatch(/demo/i)
    expect(DEMO_NOTICE).toMatch(/sint/i)
  })

  it("never claims a payment happened", () => {
    const surface = [DEMO_NOTICE, SPECIALISTS, DEMO_CONVERSATIONS, DEMO_THREAD]
    for (const text of collectStrings(surface)) {
      for (const pattern of forbidden) {
        expect(pattern.test(text), `"${text}" matched ${pattern}`).toBe(false)
      }
    }
  })
})

describe("product identity", () => {
  const promo = [
    /create-next-app/i,
    /nextjs\.org/i,
    /vercel\.com/i,
    /ai teammates/i,
    /generated by create next app/i,
  ]

  it("keeps template and reference promotion out of the app sources", () => {
    // Only the surface we author: generated files (next-env.d.ts, .next) and
    // vendored registry components are out of scope.
    const files = ["app", "components", "lib", "hooks"].flatMap((dir) =>
      sourceFiles(resolve(APP_ROOT, dir))
    )
    expect(files.length).toBeGreaterThan(5)
    for (const file of files) {
      const contents = readFileSync(file, "utf8")
      for (const pattern of promo) {
        expect(pattern.test(contents), `${relative(APP_ROOT, file)} matched ${pattern}`).toBe(
          false
        )
      }
    }
  })
})
